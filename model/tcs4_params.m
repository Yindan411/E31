function p = tcs4_params(varargin)
%TCS4_PARAMS  四轮版 TCS-PID 仿真模型的“唯一参数源”
%
%   p = tcs4_params()                  % 默认工况：干地(mu=1.4)，全油门直线加速
%   p = tcs4_params('mu_road',0.5)     % 覆盖任意字段，例如把路面附着改成 0.5(湿地)
%
%   所有 Simulink 模块里写的都是 p.xxx，所以：
%   改参数 -> 重新运行这个函数 -> 直接 sim，不需要改模型、也不需要重新生成模型。
%
%   单位约定：N, m, s, rad/s, rpm, N*m, kg
%   整车现状：FSEC 四电机 AMK DD5 分布式驱动，无 GPS/IMU/踏板位移传感器以外的外测传感器，
%             轮速来自电机自带编码器(电机转速/减速比折算)，参考车速由四轮转速估计。
% -------------------------------------------------------------------------

%% 0. 工况与仿真设置 ------------------------------------------------------
p.t_end      = 8.0;      % 仿真总时长 [s]
p.v0         = 0.0;      % 初始车速 [m/s]
p.Ts         = 0.02;     % 控制器采样周期 [s]（20 ms，与实车 VCU 周期一致）
p.Ts_plant   = 5e-4;     % 被控对象积分步长 [s]（0.5 ms，固定步长 ode4）
p.TCS_enable = 1;        % 总开关：1=TCS 工作，0=TCS 关闭（做对比实验用）

% 车手油门开度曲线（时间 -> 踏板 0~1），1-D 查表，线性插值
p.drv_t      = [0  0.30 1.10 8.0];
p.drv_pedal  = [0  0.00 1.00 1.00];

% 路面附着随时间变化（时间 -> mu），1-D 查表，零阶保持（可做“干地->湿地”阶跃）
p.mu_road = 1.40;                                    % 默认：干燥沥青
p.mu_t    = [0 1e9];
p.mu_v    = [1.40 1.40];

%% 1. 整车参数（FSEC 四电机赛车，与旧版模型保持一致便于对照）--------------
p.m        = 250;        % 整车质量（含车手）[kg]
p.g        = 9.81;       % 重力加速度 [m/s^2]
p.L        = 1.565;      % 轴距 [m]
p.a_cg     = 0.845;      % 质心到前轴距离 [m]
p.b_cg     = 0.720;      % 质心到后轴距离 [m]
p.h_cg     = 0.30;       % 质心高度 [m]
p.CdA      = 1.00;       % 风阻系数 x 迎风面积 [m^2]
p.rho_air  = 1.225;      % 空气密度 [kg/m^3]
p.f_rr     = 0.015;      % 滚动阻力系数 [-]

%% 2. 轮胎参数（Hoosier 16x7.5-10，简化为“滑移率-附着系数”曲线）---------
p.r_w      = 0.198;      % 轮胎滚动半径 [m]
p.mu_peak  = 1.40;       % 干燥沥青峰值附着系数 [-]
p.B_pac    = 10.75;      % 魔术公式刚度因子（决定滑移率-附着曲线的上升斜率）
p.C_pac    = 1.65;       % 魔术公式形状因子
p.v_floor  = 1.0;        % 计算滑移率时车速的下限 [m/s]，防止低速除零把滑移率算爆

% 每个“角落(单轮)”的等效转动惯量 = 车轮 + 1台电机+减速器折算到轮端
%   J_corner = J_wheel + J_rotor*i^2 ；J_rotor 约 0.005 kg*m^2
p.J_fl = 0.45;  p.J_fr = 0.45;    % 前轮（i=11.8）[kg*m^2]
p.J_rl = 0.525; p.J_rr = 0.525;   % 后轮（i=13.2）[kg*m^2]

%% 3. 电机与传动（4 x AMK DD5-14-10-POW-18600 轮边电机）------------------
p.T_mot_max = 21.0;      % 单台电机峰值扭矩 [N*m]
p.n_base    = 9100;      % 基速（恒扭矩区结束）[rpm]
p.n_max     = 18600;     % 最高转速 [rpm]
p.T_at_maxn = 10.3;      % 最高转速处的扭矩 [N*m]（恒功率段）
p.i_f       = 11.8;      % 前轴减速比
p.i_r       = 13.2;      % 后轴减速比
p.eta_drv   = 0.89;      % 传动效率（电机 0.92 x 减速器 0.97）

% 电机外特性（以“电机转速”为横轴）：0->21, 9100->21, 18600->10.3, 超速后归零
p.n_bp      = [0 p.n_base p.n_max 1.25*p.n_max];
p.T_curve   = [p.T_mot_max p.T_mot_max p.T_at_maxn 0];

% ---- 油门开度 x 转速 的二维扭矩查表（这是新版的核心改动）----------------
% 横轴换成“车轮转速[rpm]”后，前/后轴因为减速比不同，同一路面下可用扭矩曲线自然错开，
% 这样“前后轴用不同查表曲线”就是真实物理，而不是人为造两条不一样的表。
% 表内容 = pedal(0~1) 外推到 [0 0.2 0.5 0.8 1.0] 五行 x 转速四列，每行 = 该油门下的外特性。
p.pedal_bp  = [0 0.2 0.5 0.8 1.0];                 % 油门开度断点
p.w_bp_f    = p.n_bp ./ p.i_f * 1;                 % 前轴断点：电机转速换算成“车轮转速[rpm]”
p.w_bp_r    = p.n_bp ./ p.i_r * 1;                 % 后轴断点
p.T_map     = (p.pedal_bp.' * p.T_curve);          % 5 x 4：行=油门，列=转速，可分离查表

%% 4. TCS / PID 参数 ------------------------------------------------------
p.lam_ref   = 0.12;      % 目标滑移率（轮胎峰值 0.13 略偏小一侧 -> 工作在稳定分支）
p.lam_on    = 0.18;      % 介入阈值：滑移率高于此值 -> TCS 介入
p.lam_off   = 0.05;      % 退出阈值：滑移率低于此值 -> TCS 退出（滞环防反复开关）
p.speed_ref_mode = 2;    % 参考车速来源：2=直接使用输入的参考车速(默认,相当于给定理想车速)  1=四轮取小估计(无GPS的替代方案,用于对照实验)
p.v_min     = 0.15;      % 车速门限 [m/s]：低于该车速不介入（防止原地误触发）

p.tau_slip  = 0.03;      % 滑移率低通滤波时间常数 [s]（抑制轮速信号噪声）
p.tau_ref   = 0.05;      % 参考车速估计的低通滤波时间常数 [s]
p.tau_en    = 0.04;      % 介入/退出平滑时间常数 [s]（避免扭矩突变）
p.tau_d     = 0.02;      % 微分项低通滤波时间常数 [s]
p.tau_tq    = 0.03;      % 扭矩指令一阶平滑时间常数 [s]（模拟电机扭矩响应）
p.tq_rate   = 200;       % 扭矩指令变化率上限 [N*m/s]（防止扭矩突变）
p.tau_relax = 0.04;      % 轮胎滑移率松弛时间常数 [s]（轮胎不是瞬时响应的）

p.Kp        = 20.0;      % 比例增益 [N*m / 单位滑移率]
p.Ki        = 20.0;      % 积分增益 [N*m / (单位滑移率 * s)]
p.Kd        = 0.0;       % 微分增益（默认 0：D 对轮速噪声敏感，答辩时这是加分点）

p.comp_ratio = 1.00;     % 补偿扭矩限幅 = 车手扭矩 x 该比例（1.0 = 允许把扭矩降到 0）
p.comp_abs   = p.comp_ratio*p.T_mot_max;  % 内部抗饱和用的绝对限幅 [N*m]

%% 5. 允许用 name-value 覆盖任意参数 --------------------------------------
for k = 1:2:numel(varargin)
    name = varargin{k};
    if ~isfield(p, name)
        warning('tcs4_params:badField','忽略未知参数名: %s', name);
        continue
    end
    p.(name) = varargin{k+1};
end

%% 6. 派生量（不要手改，会自动算）----------------------------------------
p.drv_t(end)   = max(p.drv_t(end), p.t_end);
p.mu_t(end)    = max(p.mu_t(end),  p.t_end);
p.alpha_slip   = p.Ts/(p.tau_slip + p.Ts);        % 滑移率低通系数
p.alpha_ref    = p.Ts/(p.tau_ref  + p.Ts);        % 参考车速低通系数
p.alpha_en     = p.Ts/(p.tau_en   + p.Ts);        % 介入平滑系数
p.alpha_d      = p.Ts/(p.tau_d    + p.Ts);        % 微分滤波系数
p.alpha_tq     = p.Ts/(p.tau_tq   + p.Ts);        % 扭矩平滑系数
p.alpha_relax  = p.Ts_plant/(p.tau_relax + p.Ts_plant);  % 轮胎松弛系数
p.lam_p        = tan(pi/(2*p.C_pac))/p.B_pac;     % 峰值滑移率（魔术公式导数=0）
end
